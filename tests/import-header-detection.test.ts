/**
 * Smart Header Detection Tests — detectHeaderRow and extractMergedRanges.
 *
 * Tests the header-detection heuristics that identify which row in an
 * imported spreadsheet contains column headers vs. title rows, blank rows,
 * or data rows.
 */
import { describe, it, expect, vi } from 'vitest'

// Mock Electron + database to prevent transitive import of `app`
vi.mock('electron', () => ({ app: { isPackaged: false, getPath: () => '/tmp' } }))
vi.mock('../src/main/database', () => ({ getDb: () => null }))
vi.mock('../src/main/logger', () => ({ logger: { info: () => {}, error: () => {}, warn: () => {} } }))

import { detectHeaderRow, extractMergedRanges } from '../src/main/import'
import type { HeaderDetectionResult } from '../src/main/import'

describe('detectHeaderRow', () => {
  it('simple file with headers on row 1 → index 0, confidence high', () => {
    const rows = [
      ['Name', 'Email', 'Phone', 'DOB'],
      ['John Doe', 'john@example.com', '555-1234', '1990-01-15'],
      ['Jane Smith', 'jane@example.com', '555-5678', '1985-03-22'],
    ]
    const result = detectHeaderRow(rows)
    expect(result.headerRowIndex).toBe(0)
    expect(result.confidence).toBe('high')
  })

  it('title row + blank row + headers on row 3 → index 2', () => {
    const rows = [
      ['My Caseload Report', '', '', ''],
      ['', '', '', ''],
      ['First', 'Last', 'DOB', 'PHQ9', 'POC'],
      ['Alice', 'Johnson', '1990-01-01', '12', '2026-01-15'],
      ['Bob', 'Brown', '1988-05-10', '8', '2026-02-20'],
    ]
    const result = detectHeaderRow(rows)
    expect(result.headerRowIndex).toBe(2)
  })

  it('multiple junk rows + headers on row 5 (real-world scenario)', () => {
    const rows = [
      ['42', 'Acuity', '', '', '', ''],
      ['', '', '', '', '', ''],
      ['Report generated 2026-01-15', '', '', '', '', ''],
      ['', '', '', '', '', ''],
      ['First', 'Last', 'Billed', 'DOB', 'PHQ9', 'POC'],
      ['Alice', 'Johnson', '2026-01-01', '1990-05-15', '12', '2026-03-01'],
      ['Bob', 'Smith', '2026-01-02', '1985-11-20', '8', '2026-03-15'],
    ]
    const result = detectHeaderRow(rows)
    expect(result.headerRowIndex).toBe(4)
  })

  it('numeric "headers" → picks row with text', () => {
    const rows = [
      ['1', '2', '3', '4'],
      ['Name', 'Age', 'Score', 'Grade'],
      ['Alice', '25', '92', 'A'],
    ]
    const result = detectHeaderRow(rows)
    expect(result.headerRowIndex).toBe(1)
  })

  it('empty rows interspersed → blank rows skipped', () => {
    const rows = [
      ['', '', ''],
      ['', '', ''],
      ['Name', 'Date', 'Status'],
      ['John', '2026-01-01', 'Active'],
    ]
    const result = detectHeaderRow(rows)
    expect(result.headerRowIndex).toBe(2)
  })

  it('all rows look like data → index 0, confidence low', () => {
    const rows = [
      ['42', '2026-01-01', '100.50'],
      ['38', '2026-02-15', '200.75'],
      ['55', '2026-03-20', '150.00'],
    ]
    const result = detectHeaderRow(rows)
    expect(result.headerRowIndex).toBe(0)
    expect(result.confidence).toBe('low')
  })

  it('merged cell spanning full width → row skipped', () => {
    const rows = [
      ['Company Caseload Report — Q1 2026', '', '', '', ''],
      ['Generated by admin', '', '', '', ''],
      ['Name', 'Email', 'Phone', 'DOB', 'Status'],
      ['Alice', 'a@b.com', '555-1234', '1990-01-01', 'Active'],
    ]
    const mergedRanges = [
      { row: 0, startCol: 0, endCol: 4 },
    ]
    const result = detectHeaderRow(rows, mergedRanges)
    expect(result.headerRowIndex).toBe(2)
  })

  it('single-column title row skipped (only 1 non-empty cell)', () => {
    const rows = [
      ['Quarterly Report', '', '', ''],
      ['Name', 'Date', 'Amount', 'Category'],
      ['Alice', '2026-01-01', '100', 'Medical'],
    ]
    const result = detectHeaderRow(rows)
    expect(result.headerRowIndex).toBe(1)
  })

  it('empty input → index 0, confidence low', () => {
    const result = detectHeaderRow([])
    expect(result.headerRowIndex).toBe(0)
    expect(result.confidence).toBe('low')
  })

  it('two-row file → detects header on row 0', () => {
    const rows = [
      ['Name', 'Phone'],
      ['Alice', '555-1234'],
    ]
    const result = detectHeaderRow(rows)
    expect(result.headerRowIndex).toBe(0)
  })
})
