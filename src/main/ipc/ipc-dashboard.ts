// --- Shared query functions (each query defined exactly once) ---

function queryStats(): { totalActive: number; followUpsPending: number } {
  const totalActive = (cachedStmt('dash_total_active', `
    SELECT COUNT(DISTINCT r.id) as n FROM rows r
    JOIN grids g ON g.id = r.grid_id AND g.is_active = 1
    WHERE r.is_active = 1 AND r.deleted_at IS NULL
  `).get() as { n: number }).n

  // Same client filter as queryFollowups() so the count matches the list.
  // follow_up_date is a local calendar date, so compare against the local "today".
  const followUpsPending = (cachedStmt('dash_followups_pending', `
    SELECT COUNT(*) as n FROM case_log cl
    JOIN rows r  ON r.id = cl.row_id AND r.is_active = 1 AND r.deleted_at IS NULL
    JOIN grids g ON g.id = r.grid_id AND g.is_active = 1
    WHERE cl.follow_up_date IS NOT NULL
      AND cl.follow_up_date <= date('now', 'localtime')
      AND cl.follow_up_completed = 0
      AND cl.voided_at IS NULL
  `).get() as { n: number }).n

  return { totalActive, followUpsPending }
}

/** The soonest deadlines for the dashboard, worked out by the shared engine */
function queryDeadlines(): unknown[] {
  return loadDeadlines({ limit: QUERY_LIMITS.DASHBOARD_PRIORITY })
}

function queryFollowups(): unknown[] {
  return cachedStmt('dash_followups', `
    SELECT
      cl.id,
      cl.row_id,
      cl.content,
      cl.follow_up_date,
      g.id   AS grid_id,
      g.name AS grid_name,
      r.display_name AS client_name
    FROM case_log cl
    JOIN rows r       ON r.id = cl.row_id AND r.is_active = 1
    JOIN grids g      ON g.id = r.grid_id AND g.is_active = 1
    WHERE cl.follow_up_date IS NOT NULL
      AND cl.follow_up_completed = 0
      AND cl.voided_at IS NULL
    ORDER BY cl.follow_up_date ASC
    LIMIT ${QUERY_LIMITS.DASHBOARD_FOLLOWUPS}
  `).all()
}

function queryArchived(): unknown[] {
  return cachedStmt('dash_archived', `
    SELECT r.id, r.grid_id, r.archived_at, r.archived_reason, g.name AS grid_name,
           r.display_name AS client_name
    FROM rows r
    JOIN grids g ON g.id = r.grid_id
    WHERE r.is_active = 0 AND r.archived_at IS NOT NULL AND r.deleted_at IS NULL
    ORDER BY r.archived_at DESC
    LIMIT ${QUERY_LIMITS.DASHBOARD_COMPLETIONS}
  `).all()
}

function queryCompleted(): unknown[] {
  return cachedStmt('dash_completed', `
    SELECT * FROM (
      SELECT
        'checklist' AS type,
        ci.id AS source_id,
        ci.title AS title,
        ci.completed_at AS completed_at,
        r.display_name AS client_name,
        g.name AS grid_name,
        ci.row_id AS row_id,
        r.grid_id AS grid_id
      FROM checklist_items ci
      JOIN rows r  ON r.id = ci.row_id AND r.deleted_at IS NULL
      JOIN grids g ON g.id = r.grid_id
      WHERE ci.is_completed = 1
        AND ci.completed_at >= date('now', '-30 days')
      ORDER BY ci.completed_at DESC
      LIMIT ${QUERY_LIMITS.DASHBOARD_COMPLETIONS}

      UNION ALL

      SELECT
        'task' AS type,
        th.id AS source_id,
        ct.title AS title,
        th.completed_at AS completed_at,
        NULL AS client_name,
        NULL AS grid_name,
        NULL AS row_id,
        ct.grid_id AS grid_id
      FROM caseload_task_history th
      JOIN caseload_tasks ct ON ct.id = th.task_id
      WHERE th.completed_at >= date('now', '-30 days')
      ORDER BY th.completed_at DESC
      LIMIT ${QUERY_LIMITS.DASHBOARD_COMPLETIONS}

      UNION ALL

      SELECT
        'deadline' AS type,
        cl.id AS source_id,
        cl.content AS title,
        cl.created_at AS completed_at,
        r2.display_name AS client_name,
        g2.name AS grid_name,
        cl.row_id AS row_id,
        r2.grid_id AS grid_id
      FROM case_log cl
      JOIN rows r2  ON r2.id = cl.row_id AND r2.deleted_at IS NULL
      JOIN grids g2 ON g2.id = r2.grid_id
      WHERE cl.log_type = 'system'
        -- M20: No dedicated completion_type column exists. The log_type='system'
        -- filter above restricts to auto-generated entries only (never user-authored),
        -- so the LIKE pattern is safe against false matches from user content.
        -- Pattern matches "{ColName} completed (was {date})" generated by
        -- ipc-cell.ts, DeadlineRow.tsx, and FocusModeView.tsx.
        AND cl.content LIKE '% completed (was %)'
        AND cl.created_at >= date('now', '-30 days')
        AND cl.voided_at IS NULL
      ORDER BY cl.created_at DESC
      LIMIT ${QUERY_LIMITS.DASHBOARD_COMPLETIONS}

      UNION ALL

      SELECT
        'followup' AS type,
        cl3.id AS source_id,
        cl3.content AS title,
        cl3.updated_at AS completed_at,
        r3.display_name AS client_name,
        g3.name AS grid_name,
        cl3.row_id AS row_id,
        r3.grid_id AS grid_id
      FROM case_log cl3
      JOIN rows r3  ON r3.id = cl3.row_id AND r3.deleted_at IS NULL
      JOIN grids g3 ON g3.id = r3.grid_id
      WHERE cl3.follow_up_date IS NOT NULL
        AND cl3.follow_up_completed = 1
        AND cl3.updated_at >= date('now', '-30 days')
        AND cl3.voided_at IS NULL
      ORDER BY cl3.updated_at DESC
      LIMIT ${QUERY_LIMITS.DASHBOARD_COMPLETIONS}
    )
    ORDER BY completed_at DESC
    LIMIT ${QUERY_LIMITS.DASHBOARD_COMPLETIONS}
  `).all()
}

/**
 * Counts for the morning briefing. Deadlines use the effective due date (stored
 * date + rule interval) and the local calendar day, like the dashboard.
 */
export interface Briefing {
  overdue: number
  dueToday: number
  dueThisWeek: number
  followUpsDue: number
  tasksDue: number
  checklistDue: number
  /** Past appointments still marked scheduled (S-09) */
  needsOutcome?: number
}

function queryBriefing(): Briefing {
  const deadlines = deadlineCounts()

  const followUpsDue = (cachedStmt('dash_briefing_followups', `
    SELECT COUNT(*) AS n FROM case_log cl
    JOIN rows r  ON r.id = cl.row_id AND r.is_active = 1 AND r.deleted_at IS NULL
    JOIN grids g ON g.id = r.grid_id AND g.is_active = 1
    WHERE cl.follow_up_date IS NOT NULL AND cl.follow_up_date <= date('now', 'localtime')
      AND cl.follow_up_completed = 0 AND cl.voided_at IS NULL
  `).get() as { n: number }).n

  const tasksDue = (cachedStmt('dash_briefing_tasks', `
    SELECT COUNT(*) AS n FROM caseload_tasks ct
    LEFT JOIN grids g ON g.id = ct.grid_id
    WHERE ct.is_completed = 0 AND ct.due_date IS NOT NULL AND ct.due_date <= date('now', 'localtime')
      AND (ct.snoozed_until IS NULL OR ct.snoozed_until <= date('now', 'localtime'))
      AND (ct.grid_id IS NULL OR g.is_active = 1)
  `).get() as { n: number }).n

  const checklistDue = (cachedStmt('dash_briefing_checklist', `
    SELECT COUNT(*) AS n FROM checklist_items ci
    JOIN rows r  ON r.id = ci.row_id AND r.is_active = 1 AND r.deleted_at IS NULL
    JOIN grids g ON g.id = r.grid_id AND g.is_active = 1
    WHERE ci.is_completed = 0 AND COALESCE(ci.is_archived, 0) = 0
      AND ci.due_date IS NOT NULL AND ci.due_date <= date('now', 'localtime')
  `).get() as { n: number }).n

  return { ...deadlines, followUpsDue, tasksDue, checklistDue, ...appointmentsToday(), needsOutcome: appointmentsNeedingOutcome() }
}

// --- IPC handler registration ---

export function registerDashboardHandlers(): void {
  secureWrap(IPC.DASHBOARD_GET_ALL, 'ipc-dashboard', () => {
    const stats = queryStats()
    const deadlines = queryDeadlines()
    const followUps = queryFollowups()
    const archived = queryArchived()
    return ok({ stats, deadlines, followUps, archived })
  })

  secureWrap(IPC.DASHBOARD_GET_DEADLINES, 'ipc-dashboard', () => {
    return ok(queryDeadlines())
  })

  // Latest notes across active lists, Pulse's own entries left out (W10 §4)
  secureWrap(IPC.DASHBOARD_RECENT_ACTIVITY, 'ipc-dashboard', () => {
    const rows = cachedStmt('dash_recent_activity', `
      SELECT cl.id, cl.row_id, r.grid_id, g.name AS grid_name, COALESCE(NULLIF(r.display_name, ''), '(unnamed)') AS name,
             cl.log_type, cl.content, cl.created_at
      FROM case_log cl JOIN rows r ON r.id = cl.row_id JOIN grids g ON g.id = r.grid_id
      WHERE cl.voided_at IS NULL AND cl.log_type != 'system' AND r.deleted_at IS NULL AND g.is_active = 1
      ORDER BY cl.created_at DESC, cl.id DESC LIMIT 10`).all() as Array<Omit<RecentActivityItem, 'text'> & { content: string }>
    return ok(rows.map(({ content, ...r }) => {
      const text = stripHtml(content).replace(/\s+/g, ' ').trim()
      return { ...r, text: text.length > 160 ? `${text.slice(0, 157)}…` : text }
    }))
  })

  secureWrap(IPC.DASHBOARD_GET_STATS, 'ipc-dashboard', () => {
    // overdue / dueThisWeek / dueThisMonth are derived on the frontend from the
    // DASHBOARD_GET_DEADLINES data, because they need interval_days math per rule.
    return ok(queryStats())
  })

  secureWrap(IPC.DASHBOARD_GET_FOLLOWUPS, 'ipc-dashboard', () => {
    return ok(queryFollowups())
  })

  secureWrap(IPC.DASHBOARD_GET_COMPLETED, 'ipc-dashboard', () => {
    return ok(queryCompleted())
  })

  secureWrap(IPC.DASHBOARD_GET_ARCHIVED, 'ipc-dashboard', () => {
    return ok(queryArchived())
  })

  secureWrap(IPC.DASHBOARD_GET_BRIEFING, 'ipc-dashboard', () => {
    return ok(queryBriefing())
  })
}
